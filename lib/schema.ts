import {
  boolean,
  date,
  integer,
  json,
  pgTable,
  real,
  text,
  timestamp,
  uuid,
} from "drizzle-orm/pg-core";

export const products = pgTable("products", {
  id: text("id").primaryKey(),
  kind: text("kind").notNull(),
  name: text("name").notNull(),
  brand: text("brand").notNull(),
  variant: text("variant").notNull(),
  manufacturer: text("manufacturer").notNull(),
  packPrice: integer("pack_price").notNull(),
  unitsPerPack: integer("units_per_pack").notNull(),
  unitName: text("unit_name").notNull(),
  tarMg: real("tar_mg"),
  nicotineMg: real("nicotine_mg"),
  coMg: real("co_mg"),
  lengthMm: integer("length_mm"),
  filter: boolean("filter"),
  strength: text("strength"),
  flavor: text("flavor"),
  abv: real("abv"),
  volumeMl: integer("volume_ml"),
  standardDrinks: real("standard_drinks"),
  calories: integer("calories"),
  origin: text("origin").notNull(),
  fact: text("fact").notNull(),
  artKey: text("art_key").notNull(),
  body: text("body").notNull(),
  band: text("band").notNull(),
  foil: text("foil").notNull(),
});

export const events = pgTable("events", {
  id: uuid("id").primaryKey().defaultRandom(),
  kind: text("kind").notNull(),
  productId: text("product_id").notNull(),
  productName: text("product_name").notNull(),
  brand: text("brand").notNull(),
  variant: text("variant").notNull(),
  manufacturer: text("manufacturer").notNull(),
  loggedAt: timestamp("logged_at", { withTimezone: true }).notNull(),
  timezone: text("timezone").notNull(),
  localDate: date("local_date").notNull(),
  localTime: text("local_time").notNull(),
  weekday: integer("weekday").notNull(),
  hour: integer("hour").notNull(),
  minute: integer("minute").notNull(),
  isoWeek: integer("iso_week").notNull(),
  month: integer("month").notNull(),
  year: integer("year").notNull(),
  quantity: real("quantity").notNull().default(1),
  unitCostInr: real("unit_cost_inr").notNull(),
  nicotineMg: real("nicotine_mg"),
  tarMg: real("tar_mg"),
  coMg: real("co_mg"),
  lifeMinutes: integer("life_minutes"),
  abv: real("abv"),
  volumeMl: integer("volume_ml"),
  standardDrinks: real("standard_drinks"),
  calories: integer("calories"),
  source: text("source").notNull().default("tap"),
  packPriceInr: real("pack_price_inr"),
  unitsPerPack: real("units_per_pack"),
  lengthMm: integer("length_mm"),
  strength: text("strength"),
  flavor: text("flavor"),
  dayPart: text("day_part"),
  city: text("city"),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
});

export const settings = pgTable("settings", {
  id: integer("id").primaryKey(),
  cigBaseline: integer("cig_baseline").notNull().default(8),
  drinkBaseline: integer("drink_baseline").notNull().default(2),
  timezone: text("timezone").notNull().default("Asia/Kolkata"),
  favoriteIds: json("favorite_ids").$type<string[]>().notNull(),
  drinkFavoriteIds: json("drink_favorite_ids").$type<string[]>().notNull(),
  city: text("city").notNull().default(""),
});

export type EventRow = typeof events.$inferSelect;
export type ProductRow = typeof products.$inferSelect;
export type SettingsRow = typeof settings.$inferSelect;
