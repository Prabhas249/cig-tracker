export function productById(id: string): ProductDef {
  return CATALOG.find((p) => p.id === id) ?? CATALOG.find((p) => p.id === "other-cig")!;
}

export function unitCost(p: ProductDef): number {
  return p.packPrice / p.unitsPerPack;
}

/** Estimated drinks round to rupees; cigarette reference math keeps paise. */
export function displayCost(p: ProductDef): number {
  const cost = unitCost(p);
  if (p.kind === "drink") return Math.round(cost);
  return Math.round(cost * 100) / 100;
}

export function servingLabel(p: ProductDef): string {
  const cost = displayCost(p);
  const shown = cost % 1 ? cost.toFixed(2) : String(cost);
  if (p.kind === "cig") {
    const reference = getPriceReference(p.id);
    return reference
      ? `Reference ₹${shown} / stick · pack of ${p.unitsPerPack} ₹${p.packPrice}`
      : `Estimate ₹${shown} / stick · set your actual price`;
  }
  if (p.unitName === "peg") {
    return `Estimate ₹${shown} / 30ml peg · bottle estimate ₹${p.packPrice}`;
  }
  if (p.unitName === "glass") {
    return `Estimate ₹${shown} / 150ml · bottle estimate ₹${p.packPrice}`;
  }
  return `Estimate ₹${shown} / ${p.unitName}`;
}

export function isSpiritPeg(p: ProductDef) {
  return p.kind === "drink" && p.unitName === "peg";
}
