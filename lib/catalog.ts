export type Kind = "cig" | "drink";
export type ViewKind = Kind | "all";
export type ArtKey = "cork" | "ember" | "whisky" | "beer" | "wine" | "clear";

export type ProductDef = {
  id: string;
  kind: Kind;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  packPrice: number;
  unitsPerPack: number;
  unitName: string;
  tarMg: number | null;
  nicotineMg: number | null;
  coMg: number | null;
  lengthMm: number | null;
  filter: boolean | null;
  strength: string | null;
  flavor: string | null;
  abv: number | null;
  volumeMl: number | null;
  standardDrinks: number | null;
  calories: number | null;
  origin: string;
  fact: string;
  artKey: ArtKey;
  body: string;
  band: string;
  foil: string;
};

const YIELD = "Typical Indian pack print (tar/nic/CO), not a 2026 lab assay.";
const PRICE = "KA/metro shop, Sep 2026. Logged per stick = pack MRP ÷ sticks.";
const PEG = "KA MRP after May 2026 AIB. Logged per 30ml peg = bottle ÷ 25.";

function cig(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  pack: number;
  units: number;
  tar: number;
  nic: number;
  co: number;
  mm: number;
  strength: string;
  flavor: string;
  fact: string;
  band: string;
  body?: string;
  foil?: string;
  filter?: boolean;
}): ProductDef {
  const stick = p.pack / p.units;
  return {
    id: p.id,
    kind: "cig",
    name: p.name,
    brand: p.brand,
    variant: p.variant,
    manufacturer: p.manufacturer,
    packPrice: p.pack,
    unitsPerPack: p.units,
    unitName: "stick",
    tarMg: p.tar,
    nicotineMg: p.nic,
    coMg: p.co,
    lengthMm: p.mm,
    filter: p.filter ?? true,
    strength: p.strength,
    flavor: p.flavor,
    abv: null,
    volumeMl: null,
    standardDrinks: null,
    calories: null,
    origin: "India",
    fact: `${p.fact} ₹${stick.toFixed(2)}/stick from ${p.units}s MRP ₹${p.pack}. ${PRICE} ${YIELD}`,
    artKey: "cork",
    body: p.body ?? "#f4f0e6",
    band: p.band,
    foil: p.foil ?? "#c9a227",
  };
}

function stdDrinks(ml: number, abv: number) {
  const grams = ml * (abv / 100) * 0.789;
  return Math.round((grams / 10) * 10) / 10;
}

function spiritKcal(ml: number, abv: number) {
  return Math.round(ml * (abv / 100) * 0.789 * 7);
}

function drink(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  pack: number;
  units: number;
  unitName: string;
  abv: number;
  volumeMl: number;
  calories: number;
  fact: string;
  artKey: ArtKey;
  body: string;
  band: string;
  strength?: string;
  flavor?: string;
}): ProductDef {
  const serving = p.pack / p.units;
  const std = stdDrinks(p.volumeMl, p.abv);
  return {
    id: p.id,
    kind: "drink",
    name: p.name,
    brand: p.brand,
    variant: p.variant,
    manufacturer: p.manufacturer,
    packPrice: p.pack,
    unitsPerPack: p.units,
    unitName: p.unitName,
    tarMg: null,
    nicotineMg: null,
    coMg: null,
    lengthMm: null,
    filter: null,
    strength: p.strength ?? null,
    flavor: p.flavor ?? null,
    abv: p.abv,
    volumeMl: p.volumeMl,
    standardDrinks: std,
    calories: p.calories,
    origin: "India",
    fact: `${p.fact} Serving ₹${serving.toFixed(0)}. ${p.volumeMl}ml · ${p.abv}% · ${std} std · ${p.calories} kcal.`,
    artKey: p.artKey,
    body: p.body,
    band: p.band,
    foil: "#c9a227",
  };
}

function spirit(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  bottle: number;
  abv: number;
  fact: string;
  body: string;
  band: string;
  artKey?: ArtKey;
}): ProductDef {
  return drink({
    ...p,
    pack: p.bottle,
    units: 25,
    unitName: "peg",
    volumeMl: 30,
    calories: spiritKcal(30, p.abv),
    fact: `${p.fact} ${PEG} 750ml ₹${p.bottle}.`,
    artKey: p.artKey ?? "whisky",
  });
}

