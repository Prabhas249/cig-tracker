import { getPriceReference } from "./pricing";

export type Kind = "cig" | "drink";
export type ViewKind = Kind | "all";
export type ArtKey = "cork" | "ember" | "whisky" | "beer" | "wine" | "clear";

export type ProductDef = {
  id: string;
  kind: Kind;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  packPrice: number;
  unitsPerPack: number;
  unitName: string;
  tarMg: number | null;
  nicotineMg: number | null;
  coMg: number | null;
  lengthMm: number | null;
  filter: boolean | null;
  strength: string | null;
  flavor: string | null;
  abv: number | null;
  volumeMl: number | null;
  standardDrinks: number | null;
  calories: number | null;
  origin: string;
  fact: string;
  artKey: ArtKey;
  body: string;
  band: string;
  foil: string;
};

const PEG = "Estimated 30ml serving cost = estimated bottle price ÷ 25.";

function cig(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  pack: number;
  units: number;
  mm: number;
  strength: string;
  flavor: string;
  fact: string;
  band: string;
  body?: string;
  foil?: string;
  filter?: boolean;
}): ProductDef {
  const reference = getPriceReference(p.id);
  const packPrice = reference?.packPrice ?? p.pack;
  const unitsPerPack = reference?.packSize ?? p.units;
  const priceNote = reference
    ? `Pack reference ₹${packPrice}/${unitsPerPack} (${reference.sourceLabel}); ₹${reference.unitPrice.toFixed(2)} per stick before any loose-stick markup.`
    : "Exact current pack price has not been verified. Set the price you paid.";
  return {
    id: p.id,
    kind: "cig",
    name: p.name,
    brand: p.brand,
    variant: p.variant,
    manufacturer: p.manufacturer,
    packPrice,
    unitsPerPack,
    unitName: "stick",
    // Legacy measurements had no supporting pack-label evidence.
    tarMg: null,
    nicotineMg: null,
    coMg: null,
    lengthMm: p.mm,
    filter: p.filter ?? true,
    strength: p.strength,
    flavor: p.flavor,
    abv: null,
    volumeMl: null,
    standardDrinks: null,
    calories: null,
    origin: "India",
    fact: `${p.fact} ${priceNote}`,
    artKey: "cork",
    body: p.body ?? "#f4f0e6",
    band: p.band,
    foil: p.foil ?? "#c9a227",
  };
}

function stdDrinks(ml: number, abv: number) {
  const grams = ml * (abv / 100) * 0.789;
  return Math.round((grams / 10) * 10) / 10;
}

export { stdDrinks };

function spiritKcal(ml: number, abv: number) {
  return Math.round(ml * (abv / 100) * 0.789 * 7);
}

export { spiritKcal };

function drink(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  pack: number;
  units: number;
  unitName: string;
  abv: number;
  volumeMl: number;
  calories: number;
  fact: string;
  artKey: ArtKey;
  body: string;
  band: string;
  strength?: string;
  flavor?: string;
}): ProductDef {
  const serving = p.pack / p.units;
  const std = stdDrinks(p.volumeMl, p.abv);
  return {
    id: p.id,
    kind: "drink",
    name: p.name,
    brand: p.brand,
    variant: p.variant,
    manufacturer: p.manufacturer,
    packPrice: p.pack,
    unitsPerPack: p.units,
    unitName: p.unitName,
    tarMg: null,
    nicotineMg: null,
    coMg: null,
    lengthMm: null,
    filter: null,
    strength: p.strength ?? null,
    flavor: p.flavor ?? null,
    abv: p.abv,
    volumeMl: p.volumeMl,
    standardDrinks: std,
    calories: p.calories,
    origin: "India",
    fact: `${p.fact} Estimated serving ₹${serving.toFixed(0)}. Prices vary by state, store and venue. ${p.volumeMl}ml · ${p.abv}% · ${std} standard drinks · approximately ${p.calories} kcal. Check the product label.`,
    artKey: p.artKey,
    body: p.body,
    band: p.band,
    foil: "#c9a227",
  };
}

function spirit(p: {
  id: string;
  name: string;
  brand: string;
  variant: string;
  manufacturer: string;
  bottle: number;
  abv: number;
  fact: string;
  body: string;
  band: string;
  artKey?: ArtKey;
}): ProductDef {
  return drink({
    ...p,
    pack: p.bottle,
    units: 25,
    unitName: "peg",
    volumeMl: 30,
    calories: spiritKcal(30, p.abv),
    fact: `${p.fact} ${PEG} Estimated 750ml bottle ₹${p.bottle}.`,
    artKey: p.artKey ?? "whisky",
  });
}

